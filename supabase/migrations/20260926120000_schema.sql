-- Tables for Foodie Match. See SPEC.md "Data model"; rules in DECISIONS.md.
-- Internal helpers live in schema `private`, which is not exposed by the API.

create schema if not exists private;

create table public.couples (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  dissolved_at timestamptz
);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null check (char_length(btrim(display_name)) between 1 and 40),
  email text not null unique check (email = lower(btrim(email))),
  couple_id uuid references public.couples (id) on delete set null,
  created_at timestamptz not null default now()
);
create index profiles_couple_id_idx on public.profiles (couple_id);

-- 6 chars, no 0/O/1/I/L.
create table public.pairing_codes (
  code text primary key check (code ~ '^[A-HJKMNP-Z2-9]{6}$'),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  used_at timestamptz
);
create index pairing_codes_owner_idx on public.pairing_codes (owner_id);

create table public.pairing_invites (
  id uuid primary key default gen_random_uuid(),
  from_user_id uuid not null references public.profiles (id) on delete cascade,
  to_email text not null check (to_email = lower(btrim(to_email))),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
  created_at timestamptz not null default now()
);
create unique index pairing_invites_one_pending_idx on public.pairing_invites (from_user_id, to_email)
  where status = 'pending';
create index pairing_invites_to_email_idx on public.pairing_invites (to_email) where status = 'pending';

-- Single-parent hierarchy: excluding a parent excludes all descendants.
create table public.ingredients (
  id bigint generated by default as identity primary key,
  canonical_name text not null unique,
  category text not null default 'other',
  parent_id bigint references public.ingredients (id) on delete set null
);
create index ingredients_parent_idx on public.ingredients (parent_id);

create table public.user_excluded_ingredients (
  user_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  ingredient_id bigint not null references public.ingredients (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, ingredient_id)
);

create table public.recipes (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text,
  cook_time_min integer check (cook_time_min > 0),
  cook_time_estimated boolean not null default false,
  cuisine text,
  category text,
  instructions text[] not null default '{}',
  source text not null,
  source_id text not null,
  created_at timestamptz not null default now(),
  unique (source, source_id)
);

create table public.recipe_ingredients (
  id bigint generated by default as identity primary key,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  ingredient_id bigint not null references public.ingredients (id),
  raw_text text not null,
  position integer not null default 0
);
create index recipe_ingredients_recipe_idx on public.recipe_ingredients (recipe_id);
create index recipe_ingredients_ingredient_idx on public.recipe_ingredients (ingredient_id);

create table public.tonight_sessions (
  id uuid primary key default gen_random_uuid(),
  couple_id uuid not null references public.couples (id) on delete cascade,
  started_by uuid not null references public.profiles (id) on delete cascade,
  status text not null default 'swiping'
    check (status in ('swiping', 'picking', 'ranking', 'done', 'cancelled')),
  filters jsonb not null default '{}',
  winner_recipe_id bigint references public.recipes (id),
  created_at timestamptz not null default now(),
  completed_at timestamptz
);
-- One active session per couple.
create unique index tonight_sessions_one_active_idx on public.tonight_sessions (couple_id)
  where status in ('swiping', 'picking', 'ranking');

create table public.tonight_participants (
  session_id uuid not null references public.tonight_sessions (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  swipe_done boolean not null default false,
  rank_done boolean not null default false,
  primary key (session_id, user_id)
);

create table public.tonight_rankings (
  session_id uuid not null references public.tonight_sessions (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  rank integer not null check (rank >= 1),
  primary key (session_id, user_id, recipe_id)
);

create table public.swipes (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  context text not null check (context in ('discover', 'tonight')),
  session_id uuid references public.tonight_sessions (id) on delete cascade,
  liked boolean not null,
  created_at timestamptz not null default now(),
  check ((context = 'discover') = (session_id is null)),
  unique nulls not distinct (user_id, recipe_id, context, session_id)
);
create index swipes_discover_likes_idx on public.swipes (recipe_id, user_id)
  where context = 'discover' and liked;

-- A row = both liked + compatible when created. Hidden (not deleted) by
-- visible_matches when an exclusion is added; removed_at = user removed it.
create table public.matches (
  couple_id uuid not null references public.couples (id) on delete cascade,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  created_at timestamptz not null default now(),
  removed_at timestamptz,
  primary key (couple_id, recipe_id)
);
